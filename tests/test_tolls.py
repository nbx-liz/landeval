"""The toll request shape and the price grammar, against hand-made responses.

Every payload here is synthetic: it mirrors the *shape* of a real answer and is
generated by `fixtures/make_toll_fixtures.py`, so the grammar can be exercised
without a recorded response.

The finding these tests exist for is that **a route which owes nothing and a
request that forgot to ask both answer `travelAdvisory: {}` under HTTP 200**,
byte for byte. Nothing on the response side separates "free" from "did not
ask", so the separation is made on the request side and the cases below feed
the two indistinguishable bodies in and require different answers out.
"""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path
from typing import Any

import pytest

from landeval.tolls import (
    DEFAULT_SHAPE,
    KNOWN_JP_TOLL_PASSES,
    RequestShape,
    TollError,
    toll_yen,
)

FIXTURES = Path(__file__).parent / "fixtures" / "toll_synthetic"

# The shape the toll-bearing synthetic cases were asked under.
ASKED = RequestShape(tolls=True, toll_passes=("JP_ETC",), emission_type="GASOLINE")


def route_of(name: str) -> dict[str, Any]:
    """The first route of one synthetic response."""
    doc = json.loads((FIXTURES / f"{name}.json").read_text(encoding="utf-8"))
    routes = doc["response"]["routes"]
    assert isinstance(routes, list) and routes, f"{name} has no route"
    first = routes[0]
    assert isinstance(first, dict)
    return first


# --- the shape itself -------------------------------------------------------


def test_the_default_shape_sends_no_modifiers_and_no_extra_computations() -> None:
    """The default body carries no `routeModifiers` key at all -- not an empty
    one -- so the default has something to be identical to."""
    assert DEFAULT_SHAPE.body_extras() == {}
    assert DEFAULT_SHAPE.is_default
    assert not DEFAULT_SHAPE.tolls


def test_a_toll_shape_carries_both_halves_or_it_is_not_a_toll_shape() -> None:
    """Either half can be dropped by mistake, and either omission returns 200
    with no error, so the check has to
    be on the request we build rather than on the answer we get."""
    extras = ASKED.body_extras()
    assert extras["extraComputations"] == ["TOLLS"]
    assert extras["routeModifiers"]["tollPasses"] == ["JP_ETC"]
    assert extras["routeModifiers"]["vehicleInfo"]["emissionType"] == "GASOLINE"

    mask = ASKED.field_mask()
    assert "routes.travelAdvisory.tollInfo" in mask
    assert "routes.legs.travelAdvisory.tollInfo" in mask
    # The base fields are still there; a toll request is not a different query.
    assert "routes.duration" in mask
    assert "routes.distanceMeters" in mask


def test_the_default_shape_asks_for_no_toll_fields() -> None:
    assert "tollInfo" not in DEFAULT_SHAPE.field_mask()


def test_an_unmeasured_toll_pass_is_refused() -> None:
    """`tollPasses` names an external behaviour. The two Japanese values are the
    ones the API documents; a third is refused, because a fixture written from
    a guess inherits the guess.
    """
    assert frozenset({"JP_ETC", "JP_ETC2"}) == KNOWN_JP_TOLL_PASSES
    with pytest.raises(TollError, match="unsupported toll pass"):
        RequestShape(tolls=True, toll_passes=("JP_ETC3",))


def test_toll_passes_without_asking_for_tolls_is_refused() -> None:
    """Against the live API this mistake -- modifiers present,
    `extraComputations` absent -- returns 200 with an empty advisory."""
    with pytest.raises(TollError, match="extraComputations"):
        RequestShape(tolls=False, toll_passes=("JP_ETC",))


# --- the token that reaches the cache key -----------------------------------


def test_the_default_shape_contributes_nothing_to_the_cache_key() -> None:
    """Entries written before shapes existed are in the default shape, and
    none of them may be invalidated by it."""
    assert DEFAULT_SHAPE.token() == ""


def test_a_toll_shape_contributes_a_token() -> None:
    assert ASKED.token() != ""


def test_shapes_that_differ_get_different_tokens() -> None:
    etc2 = RequestShape(tolls=True, toll_passes=("JP_ETC2",), emission_type="HYBRID")
    assert ASKED.token() != etc2.token()


def test_the_token_does_not_depend_on_the_order_passes_were_written_in() -> None:
    a = RequestShape(tolls=True, toll_passes=("JP_ETC", "JP_ETC2"))
    b = RequestShape(tolls=True, toll_passes=("JP_ETC2", "JP_ETC"))
    assert a.token() == b.token()


# --- the cache body ---------------------------------------------------------


def test_a_shape_survives_a_round_trip_through_the_cache_body() -> None:
    assert RequestShape.from_cache(ASKED.to_cache()) == ASKED


def test_the_default_shape_writes_nothing_into_the_cache_body() -> None:
    """A default entry written today is the same bytes as one written a year
    ago, which is what keeps the existing entries from being rewritten."""
    assert DEFAULT_SHAPE.to_cache() == {}


def test_a_body_with_no_recorded_shape_reads_as_the_default() -> None:
    """An entry written without a shape. It is the default shape, and the
    default shape does not ask about tolls -- which is why the price below comes
    back as missing rather than as zero."""
    assert RequestShape.from_cache({}) == DEFAULT_SHAPE


def test_a_malformed_recorded_shape_is_an_error_not_a_default() -> None:
    """Absent means "written before the field existed". Answering the same way
    for "written wrong" hides a writer that is currently getting it wrong."""
    with pytest.raises(TollError):
        RequestShape.from_cache({"shape": {"tolls": "yes"}})


# --- the grammar, read off the priced responses -----------------------------


@pytest.mark.parametrize(
    ("name", "yen"),
    [
        ("tolled-friday-nopass", 4000),
        ("tolled-friday-etc", 1500),
        ("tolled-friday-etc2", 1500),
        ("tolled-sunday-nopass", 4000),
        ("tolled-sunday-etc", 1200),
    ],
)
def test_a_priced_route_reads_back_the_amount_that_was_returned(name: str, yen: int) -> None:
    assert toll_yen(route_of(name), ASKED) == yen


def test_a_genuinely_free_route_reads_as_zero_when_the_question_was_asked() -> None:
    """A short surface-road route, asked properly: `travelAdvisory` is present
    and empty."""
    assert toll_yen(route_of("free-friday-etc"), ASKED) == 0


def test_the_same_body_reads_as_missing_when_the_question_was_not_asked() -> None:
    """The pair that makes this module necessary. The body is the same one as
    the case above; only the recorded request differs, and the answer has to
    differ with it."""
    assert toll_yen(route_of("free-friday-etc"), DEFAULT_SHAPE) is None


def test_a_body_from_a_request_that_forgot_extra_computations_is_never_zero() -> None:
    """First half. A request without `extraComputations` returns exactly what a
    free route returns. Read under the shape that was actually sent -- one
    without `extraComputations` -- it has to come back missing."""
    sent = DEFAULT_SHAPE
    assert toll_yen(route_of("mask-without-extracomputations"), sent) is None


def test_a_body_from_a_request_that_forgot_the_mask_is_an_error() -> None:
    """Second half. A request without the mask gets no `travelAdvisory` at
    all, still under HTTP 200. A shape that says the
    question was asked cannot be reconciled with an answer that has no place to
    put it, and guessing zero is the failure this module exists to prevent."""
    with pytest.raises(TollError, match="travelAdvisory"):
        toll_yen(route_of("extracomputations-without-mask"), ASKED)


def test_the_production_shaped_response_reads_as_missing() -> None:
    """The default shape is the body the pipeline sends."""
    assert toll_yen(route_of("production-shape-nomodifiers"), DEFAULT_SHAPE) is None


# --- the grammar's closed edges --------------------------------------------


def priced(*entries: dict[str, Any]) -> dict[str, Any]:
    return {"travelAdvisory": {"tollInfo": {"estimatedPrice": list(entries)}}}


def test_a_missing_nanos_is_zero_not_an_error() -> None:
    """A JPY amount can come without `nanos`; the documented example is USD,
    where it is present. A parser requiring it would refuse such an answer."""
    assert toll_yen(priced({"currencyCode": "JPY", "units": "1500"}), ASKED) == 1500


def test_a_zero_nanos_is_accepted() -> None:
    assert toll_yen(priced({"currencyCode": "JPY", "units": "10", "nanos": 0}), ASKED) == 10


def test_a_non_zero_nanos_is_an_error_not_a_rounding() -> None:
    with pytest.raises(TollError, match="nanos"):
        toll_yen(priced({"currencyCode": "JPY", "units": "10", "nanos": 500}), ASKED)


def test_a_currency_that_is_not_yen_is_an_error() -> None:
    with pytest.raises(TollError, match="currency"):
        toll_yen(priced({"currencyCode": "USD", "units": "10"}), ASKED)


def test_more_than_one_price_is_an_error_not_a_sum() -> None:
    """Summing across currencies would invent a number; taking the
    first would drop one silently. Both are worse than refusing."""
    with pytest.raises(TollError, match="one price"):
        toll_yen(
            priced(
                {"currencyCode": "JPY", "units": "10"},
                {"currencyCode": "JPY", "units": "20"},
            ),
            ASKED,
        )


def test_an_empty_price_list_is_an_error_not_free() -> None:
    """`tollInfo` present with nothing in it is outside the grammar. Zero is
    what a *missing* `tollInfo` means, and reading another shape the same way is
    how the two get confused."""
    with pytest.raises(TollError, match="estimatedPrice"):
        toll_yen(priced(), ASKED)


def test_units_that_are_not_an_integer_string_are_an_error() -> None:
    with pytest.raises(TollError, match="units"):
        toll_yen(priced({"currencyCode": "JPY", "units": "1500.5"}), ASKED)


def test_units_given_as_a_number_are_an_error() -> None:
    """The API returns a string. Accepting an int too would mean the reader has
    two grammars and only one of them is the documented type."""
    with pytest.raises(TollError, match="units"):
        toll_yen(priced({"currencyCode": "JPY", "units": 1500}), ASKED)


# --- the refusals that keep a wrong body from being read at all -------------


def test_an_unknown_emission_type_is_refused() -> None:
    with pytest.raises(TollError, match="emission type"):
        RequestShape(tolls=True, emission_type="STEAM")


@pytest.mark.parametrize(
    ("body", "match"),
    [
        ({"shape": []}, "not an object"),
        ({"shape": {"tolls": True, "toll_passes": "JP_ETC"}}, "toll_passes"),
        ({"shape": {"tolls": True, "toll_passes": [1]}}, "toll_passes"),
        ({"shape": {"tolls": True, "emission_type": 3}}, "emission_type"),
    ],
)
def test_a_cache_body_that_cannot_be_read_raises_rather_than_defaulting(
    body: dict[str, Any], match: str
) -> None:
    """Each of these would otherwise become the default shape, and the default
    shape reports every price missing -- a wrong body would look like an old one
    and go quiet forever."""
    with pytest.raises(TollError, match=match):
        RequestShape.from_cache(body)


@pytest.mark.parametrize(
    ("route", "match"),
    [
        ({"travelAdvisory": []}, "travelAdvisory is not an object"),
        ({"travelAdvisory": {"tollInfo": []}}, "tollInfo is not an object"),
        (
            {"travelAdvisory": {"tollInfo": {"estimatedPrice": ["JPY 10"]}}},
            "price entry is not an object",
        ),
        (
            {
                "travelAdvisory": {
                    "tollInfo": {
                        "estimatedPrice": [{"currencyCode": "JPY", "units": "10", "nanos": "0"}]
                    }
                }
            },
            "nanos is not an integer",
        ),
    ],
)
def test_a_response_shape_outside_the_grammar_raises(route: dict[str, Any], match: str) -> None:
    with pytest.raises(TollError, match=match):
        toll_yen(route, ASKED)


# --- axes of the grammar that must not be left open ---------------------------
#
# Every one of them is the same mistake in a different place: a key read with
# `.get()` answers an explicit JSON `null` -- which the API does not send -- as
# if the key had been absent, and absence is the form that means something.


def test_a_null_toll_info_is_not_a_free_route() -> None:
    """`{"tollInfo": null}` is the API saying something, and it is not the thing
    an absent key says; it must not be read as 0."""
    with pytest.raises(TollError, match="tollInfo"):
        toll_yen({"travelAdvisory": {"tollInfo": None}}, ASKED)


def test_a_null_travel_advisory_is_not_an_answer() -> None:
    with pytest.raises(TollError, match="travelAdvisory"):
        toll_yen({"travelAdvisory": None}, ASKED)


def test_a_null_shape_in_a_cache_body_is_malformed_not_legacy() -> None:
    """The dangerous direction: a broken body wearing an old body's clothes.
    Legacy entries have no `shape` key at all."""
    with pytest.raises(TollError, match="not an object"):
        RequestShape.from_cache({"shape": None})


@pytest.mark.parametrize("units", ["-1", "+1", " 1", "1_0", "-0", "０", "01", "1.0", ""])
def test_units_outside_the_canonical_spelling_are_refused(units: str) -> None:
    """The spelling is policed as well as the type. `int()` accepts a
    sign, surrounding space, underscore separators and full-width digits, and
    answers 1, 1, 10 and 0 for values outside the grammar -- so a malformed
    amount would become a confident number. The negative case is refused
    here rather than by a numeric bound: no sign is admissible at all."""
    with pytest.raises(TollError, match="units"):
        toll_yen(priced({"currencyCode": "JPY", "units": units}), ASKED)


def test_the_canonical_spellings_still_parse() -> None:
    """The other direction: the canonical amounts the synthetic responses carry."""
    for units, expected in (("0", 0), ("1200", 1200), ("1500", 1500), ("4000", 4000)):
        assert toll_yen(priced({"currencyCode": "JPY", "units": units}), ASKED) == expected


def test_zero_yen_is_still_a_price_the_grammar_accepts() -> None:
    """The bound is at zero, not above it."""
    assert toll_yen(priced({"currencyCode": "JPY", "units": "0"}), ASKED) == 0


def test_an_emission_type_without_tolls_is_refused() -> None:
    """It would reach neither the wire nor the mask, but it would change the
    cache key and the cache body -- so the request, the key and the entry would
    each describe a different question."""
    with pytest.raises(TollError, match="without asking for tolls"):
        RequestShape(tolls=False, emission_type="GASOLINE")


def test_a_duplicate_toll_pass_is_refused() -> None:
    with pytest.raises(TollError, match="duplicate"):
        RequestShape(tolls=True, toll_passes=("JP_ETC2", "JP_ETC2"))


def test_passes_are_canonical_so_one_digest_holds_one_shape() -> None:
    """`token()` sorts, and therefore declares the two orderings the same
    question. Were the field not canonical, one key would hold two shapes that
    compare unequal, and the cache reader would refuse an entry it had written
    itself."""
    a = RequestShape(tolls=True, toll_passes=("JP_ETC", "JP_ETC2"))
    b = RequestShape(tolls=True, toll_passes=("JP_ETC2", "JP_ETC"))

    assert a.token() == b.token()
    assert a == b
    assert a.to_cache() == b.to_cache()


@pytest.mark.parametrize(
    ("kwargs", "match"),
    [
        ({"tolls": 1}, "boolean"),
        ({"tolls": "yes"}, "boolean"),
        ({"tolls": True, "toll_passes": ["JP_ETC2"]}, "tuple"),
    ],
)
def test_a_shape_that_its_own_reader_would_refuse_cannot_be_built(
    kwargs: dict[str, object], match: str
) -> None:
    """`from_cache` requires a real boolean and a real tuple. Without the same
    checks on the way in, `RequestShape(tolls=1)` would send a toll-bearing
    request, write `"tolls": 1` into the body, and be refused when that entry
    was read back -- the two ends of one round trip disagreeing about what a value
    is."""
    with pytest.raises(TollError, match=match):
        RequestShape(**kwargs)  # type: ignore[arg-type]


# --- the synthetic payloads are generated, not hand-edited -------------------


def test_the_synthetic_payloads_regenerate_byte_for_byte() -> None:
    """The files under `fixtures/toll_synthetic/` are the output of one script.
    A hand edit, or a change to the script that was not followed by a rewrite,
    would leave the checked-in copy describing something the script does not
    make."""
    script = Path(__file__).parent / "fixtures" / "make_toll_fixtures.py"
    spec = importlib.util.spec_from_file_location("make_toll_fixtures", script)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)

    expected = module.expected_files()
    present = sorted(path.name for path in FIXTURES.glob("*.json"))

    assert present == sorted(expected)
    for name, text in expected.items():
        assert (FIXTURES / name).read_text(encoding="utf-8") == text, name


# --- no response value is quoted ------------------------------------------

SECRET_IN_ECHO = "synthetic\\toll-key"  # noqa: S105 - a fixture, not a credential


def _priced(price: object) -> dict[str, Any]:
    return {"travelAdvisory": {"tollInfo": {"estimatedPrice": [price]}}}


# (the route, the field the message names, what it says of the value)
ECHOING_ROUTES = [
    pytest.param(
        {"travelAdvisory": {"tollInfo": {"note": SECRET_IN_ECHO}}},
        "tollInfo",
        "dict, 1 items",
        id="no-price",
    ),
    pytest.param(
        {"travelAdvisory": {"tollInfo": {"estimatedPrice": [SECRET_IN_ECHO, SECRET_IN_ECHO]}}},
        "estimatedPrice",
        "got 2",
        id="two-prices",
    ),
    pytest.param(
        _priced({"currencyCode": SECRET_IN_ECHO, "units": "1"}),
        "currencyCode",
        f"str, {len(SECRET_IN_ECHO)} chars",
        id="currency",
    ),
    pytest.param(
        _priced({"currencyCode": "JPY", "units": "1", "nanos": SECRET_IN_ECHO}),
        "nanos",
        f"str, {len(SECRET_IN_ECHO)} chars",
        id="nanos",
    ),
    pytest.param(
        _priced({"currencyCode": "JPY", "units": [SECRET_IN_ECHO]}),
        "units",
        "list, 1 items",
        id="units-type",
    ),
    pytest.param(
        _priced({"currencyCode": "JPY", "units": SECRET_IN_ECHO}),
        "units",
        f"str, {len(SECRET_IN_ECHO)} chars",
        id="units-spelling",
    ),
]


@pytest.mark.parametrize(("route", "field", "described"), ECHOING_ROUTES)
def test_a_refused_value_is_named_and_described_never_quoted(
    route: dict[str, Any], field: str, described: str
) -> None:
    """The message says which field and what kind of value, and holds no
    spelling of the value: raw, or as `repr` or `json.dumps` write it."""
    with pytest.raises(TollError) as refused:
        toll_yen(route, ASKED)

    message = str(refused.value)
    assert field in message
    assert described in message
    for spelling in (
        SECRET_IN_ECHO,
        repr(SECRET_IN_ECHO)[1:-1],
        json.dumps(SECRET_IN_ECHO)[1:-1],
        "toll-key",
    ):
        assert spelling not in message


@pytest.mark.parametrize(
    ("body", "field"),
    [
        pytest.param({"shape": {"tolls": SECRET_IN_ECHO}}, "shape.tolls", id="tolls"),
        pytest.param(
            {"shape": {"tolls": True, "toll_passes": SECRET_IN_ECHO}},
            "shape.toll_passes",
            id="passes-type",
        ),
        pytest.param(
            {"shape": {"tolls": True, "toll_passes": [SECRET_IN_ECHO]}},
            "toll_passes: list, 1 items",
            id="passes-value",
        ),
        pytest.param(
            {"shape": {"tolls": True, "emission_type": [SECRET_IN_ECHO]}},
            "shape.emission_type",
            id="emission-type",
        ),
        pytest.param(
            {"shape": {"tolls": True, "emission_type": SECRET_IN_ECHO}},
            f"emission_type: str, {len(SECRET_IN_ECHO)} chars",
            id="emission-value",
        ),
    ],
)
def test_a_cached_shape_is_refused_without_quoting_it(body: dict[str, Any], field: str) -> None:
    with pytest.raises(TollError) as refused:
        RequestShape.from_cache(body)

    message = str(refused.value)
    assert field in message
    assert "toll-key" not in message
    assert refused.value.__context__ is None


def test_a_shape_a_caller_writes_is_still_refused_by_name() -> None:
    """The constructor keeps quoting the value it refuses: that text is the
    caller's own configuration, not a response or a cache body."""
    with pytest.raises(TollError, match="'JP_ETC9'"):
        RequestShape(tolls=True, toll_passes=("JP_ETC9",))


def test_the_public_toll_function_keeps_its_signature() -> None:
    """The signature is the one this PR started from. A new parameter on
    `toll_yen` would be a public API change, which needs its own proposal."""
    import inspect

    assert str(inspect.signature(toll_yen)) == (
        "(route: 'dict[str, Any]', shape: 'RequestShape') -> 'int | None'"
    )
